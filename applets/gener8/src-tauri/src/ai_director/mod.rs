#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BeatEntry {
    pub time_ms: u64,
    pub beat_type: String,
    pub energy: f32,
    pub section_label: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Section {
    pub start_ms: u64,
    pub end_ms: u64,
    pub label: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BeatMap {
    pub bpm: f32,
    pub duration_ms: u64,
    pub beats: Vec<BeatEntry>,
    pub sections: Vec<Section>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Shot {
    pub shot_id: String,
    pub start_ms: u64,
    pub end_ms: u64,
    pub visual_prompt: String,
    pub shot_type: String,
    pub reference_tags: Vec<String>,
    /// How the initial frame for this shot is sourced.
    pub init_source: InitSource,
}

/// How the initial frame for a video shot is sourced. This controls the
/// render pipeline: keyframe-generated shots need an image engine pass
/// before the video engine can extend them; user-provided shots skip the
/// keyframe step entirely.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum InitSource {
    /// Keyframe will be generated by an image engine (e.g. 1magen).
    /// The render_sequence places these in the image batch first.
    KeyframeGenerated {
        /// Prompt for keyframe generation (may differ from shot visual_prompt).
        keyframe_prompt: String,
    },
    /// Initial frame is the last frame of the previous shot.
    /// No keyframe generation needed; video engine continues from prior output.
    PreviousShotEndFrame {
        /// shot_id of the preceding shot.
        previous_shot_id: String,
    },
    /// User has provided the initial frame directly (uploaded image).
    /// No keyframe generation needed.
    UserProvided {
        /// Path or FileRef to the user-supplied image.
        image_path: String,
    },
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ShotPlan {
    pub shots: Vec<Shot>,
    pub style_preset: String,
    pub brief: String,
    pub total_duration_ms: u64,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlanShotsParams {
    pub audio_path: String,
    pub beat_map: BeatMap,
    pub brief: String,
    pub style_preset: String,
    #[serde(default)]
    pub target_duration_ms: Option<u64>,
    #[serde(default)]
    pub model: Option<String>,
}

// ---------------------------------------------------------------------------
// Render sequence
// ---------------------------------------------------------------------------

/// A single step in the render sequence. Either generate a keyframe image
/// or extend a shot into video.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "engine", rename_all = "snake_case")]
pub enum RenderStep {
    /// Generate a keyframe image via an image engine (e.g. 1magen).
    ImageKeyframe {
        shot_id: String,
        prompt: String,
        /// Index of this keyframe in the overall sequence (for ordering).
        sequence_index: usize,
    },
    /// Generate a video segment from an initial frame via a video engine (e.g. 3nvizen).
    VideoSegment {
        shot_id: String,
        start_ms: u64,
        end_ms: u64,
        visual_prompt: String,
        /// Reference to the initial frame (output of a prior ImageKeyframe step,
        /// or a user-provided image, or the end frame of a previous VideoSegment).
        init_frame_ref: String,
        sequence_index: usize,
    },
}

/// Build a render sequence from a ShotPlan. Groups all keyframe generation
/// steps first (for the image engine), then all video extension steps
/// (for the video engine). This minimizes VRAM swaps between engines.
///
/// Invariant: within each group, steps are ordered by shot sequence
/// (first shot first). Cross-engine dependencies are resolved by the
/// shell router's job graph; we just need the grouping here.
pub fn render_sequence(plan: &ShotPlan) -> Vec<RenderStep> {
    let mut image_steps: Vec<RenderStep> = Vec::new();
    let mut video_steps: Vec<RenderStep> = Vec::new();
    let mut global_idx: usize = 0;

    for shot in &plan.shots {
        // Phase 1: keyframe generation (if needed)
        match &shot.init_source {
            InitSource::KeyframeGenerated { keyframe_prompt } => {
                image_steps.push(RenderStep::ImageKeyframe {
                    shot_id: shot.shot_id.clone(),
                    prompt: keyframe_prompt.clone(),
                    sequence_index: global_idx,
                });
                global_idx += 1;
            }
            InitSource::UserProvided { .. } | InitSource::PreviousShotEndFrame { .. } => {
                // No keyframe generation needed
            }
        }

        // Phase 2: video extension
        let init_frame_ref = match &shot.init_source {
            InitSource::KeyframeGenerated { .. } => {
                // Will be resolved to the output of the ImageKeyframe step
                format!("keyframe:{}", shot.shot_id)
            }
            InitSource::PreviousShotEndFrame { previous_shot_id } => {
                format!("endframe:{}", previous_shot_id)
            }
            InitSource::UserProvided { image_path } => {
                format!("user:{}", image_path)
            }
        };

        video_steps.push(RenderStep::VideoSegment {
            shot_id: shot.shot_id.clone(),
            start_ms: shot.start_ms,
            end_ms: shot.end_ms,
            visual_prompt: shot.visual_prompt.clone(),
            init_frame_ref,
            sequence_index: global_idx,
        });
        global_idx += 1;
    }

    // All image keyframes first (batched for 1magen), then all video segments
    // (batched for 3nvizen). Shell router handles VRAM swap between phases.
    let mut sequence = Vec::with_capacity(image_steps.len() + video_steps.len());
    sequence.extend(image_steps);
    sequence.extend(video_steps);
    sequence
}

