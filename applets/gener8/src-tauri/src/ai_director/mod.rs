//! AI Director: shot planning, beat analysis, and render sequencing.
//!
//! Ported from S3 Studio's `ai_director/`. Key migration changes:
//!   - No Tauri commands; all invocation is via IPC or internal function calls
//!   - Tier gate uses AppState.tier (HMAC-verified) instead of require_creator_studio()
//!   - Added InitSource enum for keyframe provenance tracking
//!   - Added render_sequence: groups shots by engine for efficient batch execution
//!     (all 1magen keyframes first, then all 3nvizen video segments)
//!
//! Wire types match `vidDirectorApi.ts` for frontend compatibility.

pub mod shot_planner;
pub mod sapi_planner;

