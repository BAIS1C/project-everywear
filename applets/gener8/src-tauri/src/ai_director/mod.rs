#[cfg(test)]
mod tests {
    use super::*;

    fn make_test_plan() -> ShotPlan {
        ShotPlan {
            shots: vec![
                Shot {
                    shot_id: "shot-1".into(),
                    start_ms: 0,
                    end_ms: 5000,
                    visual_prompt: "cityscape at night".into(),
                    shot_type: "wide".into(),
                    reference_tags: vec![],
                    init_source: InitSource::KeyframeGenerated {
                        keyframe_prompt: "neon cityscape, wide angle".into(),
                    },
                },
                Shot {
                    shot_id: "shot-2".into(),
                    start_ms: 5000,
                    end_ms: 10000,
                    visual_prompt: "zoom into neon signs".into(),
                    shot_type: "close".into(),
                    reference_tags: vec![],
                    init_source: InitSource::PreviousShotEndFrame {
                        previous_shot_id: "shot-1".into(),
                    },
                },
                Shot {
                    shot_id: "shot-3".into(),
                    start_ms: 10000,
                    end_ms: 15000,
                    visual_prompt: "crowd dancing".into(),
                    shot_type: "medium".into(),
                    reference_tags: vec![],
                    init_source: InitSource::KeyframeGenerated {
                        keyframe_prompt: "crowd at music festival".into(),
                    },
                },
            ],
            style_preset: "cyberpunk".into(),
            brief: "Music video for electronic track".into(),
            total_duration_ms: 15000,
        }
    }

    #[test]
    fn render_sequence_groups_by_engine() {
        let plan = make_test_plan();
        let seq = render_sequence(&plan);

        // Should have 2 image keyframes first, then 3 video segments
        assert_eq!(seq.len(), 5);

        // First two should be ImageKeyframe
        assert!(
            matches!(&seq[0], RenderStep::ImageKeyframe { shot_id, .. } if shot_id == "shot-1")
        );
        assert!(
            matches!(&seq[1], RenderStep::ImageKeyframe { shot_id, .. } if shot_id == "shot-3")
        );

        // Last three should be VideoSegment
        assert!(matches!(&seq[2], RenderStep::VideoSegment { shot_id, .. } if shot_id == "shot-1"));
        assert!(matches!(&seq[3], RenderStep::VideoSegment { shot_id, .. } if shot_id == "shot-2"));
        assert!(matches!(&seq[4], RenderStep::VideoSegment { shot_id, .. } if shot_id == "shot-3"));
    }

    #[test]
    fn shot2_references_shot1_endframe() {
        let plan = make_test_plan();
        let seq = render_sequence(&plan);

        // shot-2's video segment should reference shot-1's end frame
        if let RenderStep::VideoSegment { init_frame_ref, .. } = &seq[3] {
            assert_eq!(init_frame_ref, "endframe:shot-1");
        } else {
            panic!("Expected VideoSegment at index 3");
        }
    }
}
