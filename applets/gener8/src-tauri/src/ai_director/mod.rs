/// Check that the current tier allows Creator Studio features.
pub fn require_creator_studio(tier: LicenceTier) -> Result<(), String> {
    match tier {
        LicenceTier::CreatorStudio => Ok(()),
        _ => Err(format!(
            "Creator Studio required (current tier: {})",
            tier.as_str()
        )),
    }
}

