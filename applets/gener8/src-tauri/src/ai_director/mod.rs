/// Analyse audio file -> structured BeatMap with energy + sections.
pub async fn analyze_audio(
    beats_cache: &crate::beats::BeatsCache,
    audio_path: &str,
    tier: LicenceTier,
) -> Result<BeatMap, String> {
    require_creator_studio(tier)?;

    let path = audio_path.to_string();
    let raw_beat_map = tokio::task::spawn_blocking(move || {
        crate::beats::engine::analyse(std::path::Path::new(&path), None)
    })
    .await
    .map_err(|e| format!("Beat analysis task panicked: {e}"))?
    .map_err(|e| format!("Beat analysis failed: {e}"))?;

    // Convert flat beat timestamps to structured Director BeatMap
    Ok(flat_to_director_beat_map(&raw_beat_map))
}

/// Convert a raw beats engine output to a structured Director BeatMap.
/// Simple heuristic: assign energy based on beat interval variance,
/// assign section labels based on energy contour.
fn flat_to_director_beat_map(raw: &crate::beats::engine::BeatMap) -> BeatMap {
    let beats: Vec<BeatEntry> = raw
        .beats
        .iter()
        .enumerate()
        .map(|(i, &time_ms)| {
            let beat_type = if i % 4 == 0 { "downbeat" } else { "beat" }.to_string();

            // Energy heuristic: beats near section boundaries get higher energy
            let energy = if i % 16 == 0 {
                0.9
            } else {
                0.5 + (i % 4) as f32 * 0.1
            };

            // Section label based on position
            let section_label = match (i * 100) / raw.beats.len().max(1) {
                0..=10 => "intro",
                11..=25 => "verse",
                26..=40 => "pre_chorus",
                41..=55 => "chorus",
                56..=70 => "verse",
                71..=85 => "chorus",
                _ => "outro",
            }
            .to_string();

            BeatEntry {
                time_ms,
                beat_type,
                energy,
                section_label,
            }
        })
        .collect();

    // Build sections from beat labels
    let mut sections: Vec<Section> = Vec::new();
    let mut current_label = String::new();
    let mut section_start = 0u64;

    for beat in &beats {
        if beat.section_label != current_label {
            if !current_label.is_empty() {
                sections.push(Section {
                    start_ms: section_start,
                    end_ms: beat.time_ms,
                    label: current_label.clone(),
                });
            }
            current_label = beat.section_label.clone();
            section_start = beat.time_ms;
        }
    }
    // Close final section
    if !current_label.is_empty() {
        sections.push(Section {
            start_ms: section_start,
            end_ms: raw.duration_ms,
            label: current_label,
        });
    }

    BeatMap {
        bpm: raw.bpm,
        duration_ms: raw.duration_ms,
        beats,
        sections,
    }
}

